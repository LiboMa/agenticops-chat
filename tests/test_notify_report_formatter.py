# ===========================================================================
# _to_markdown
# ===========================================================================


class TestToMarkdown:
    def test_basic(self):
        result = _to_markdown("# Hello\n\nWorld")
        assert isinstance(result, FormattedReport)
        assert result.format == "markdown"
        assert result.content == b"# Hello\n\nWorld"
        assert result.content_type == "text/markdown; charset=utf-8"
        assert result.extension == ".md"

    def test_unicode(self):
        result = _to_markdown("测试中文内容")
        assert "测试中文内容".encode("utf-8") == result.content

    def test_empty(self):
        result = _to_markdown("")
        assert result.content == b""


