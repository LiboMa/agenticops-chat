class TestFormatReport:
    def test_markdown_format(self):
        results = format_report("Test", "# Content", ["markdown"])
        assert len(results) == 1
        assert results[0].format == "markdown"
        assert results[0].extension == ".md"

    def test_html_format(self):
        results = format_report("Test Title", "## Section\n\nParagraph", ["html"])
        assert len(results) == 1
        r = results[0]
        assert r.format == "html"
        assert r.extension == ".html"
        assert r.content_type == "text/html; charset=utf-8"
        html = r.content.decode("utf-8")
        assert "Test Title" in html
        assert "<h2" in html

    def test_html_contains_template_structure(self):
        results = format_report("Report", "Body text", ["html"])
        html = results[0].content.decode("utf-8")
        assert "<!DOCTYPE html>" in html
        assert "Generated by AgenticOps" in html

    def test_multiple_formats(self):
        results = format_report("Multi", "Content", ["markdown", "html"])
        assert len(results) == 2
        formats = {r.format for r in results}
        assert formats == {"markdown", "html"}

    def test_unknown_format_skipped(self):
        results = format_report("X", "Y", ["markdown", "unknown_xyz"])
        assert len(results) == 1
        assert results[0].format == "markdown"

    def test_newsletter_html(self):
        meta = {"report_type": "newsletter", "issue_number": 42, "subtitle": "Weekly"}
        results = format_report("Newsletter", "## Topic\n\nHello", ["html"], report_metadata=meta)
        assert len(results) == 1
        html = results[0].content.decode("utf-8")
        assert "Newsletter" in html
        assert "Issue NO.42" in html
        assert "Weekly" in html

    def test_pdf_skipped_without_weasyprint(self):
        # Weasyprint is unlikely installed in test env
        results = format_report("PDF Test", "content", ["pdf"])
        # Either 0 results (not installed) or 1 (installed)
        if results:
            assert results[0].format == "pdf"

    def test_docx_skipped_without_python_docx(self):
        results = format_report("DOCX Test", "content", ["docx"])
        if results:
            assert results[0].format == "docx"

    def test_case_insensitive_format(self):
        results = format_report("T", "C", ["MARKDOWN", " HTML "])
        assert len(results) == 2

    def test_empty_formats_list(self):
        results = format_report("T", "C", [])
        assert results == []

    def test_report_metadata_default(self):
        # Should not crash when metadata is None
        results = format_report("T", "C", ["html"], report_metadata=None)
        assert len(results) == 1


