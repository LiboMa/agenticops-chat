class TestParseNewsletterItems:
    def test_contact_badge_chinese(self):
        html = "<p>联系人：张三</p>"
        result = _parse_newsletter_items(html)
        assert "128100" in result  # person emoji code
        assert "张三" in result

    def test_contact_badge_english(self):
        html = "<p>Contact: John<br /></p>"
        result = _parse_newsletter_items(html)
        assert "John" in result
        assert "128100" in result

    def test_confidentiality_badge(self):
        html = "<p>公开范围：内部<br /></p>"
        result = _parse_newsletter_items(html)
        assert "内部" in result
        assert "128274" in result  # lock emoji

    def test_no_match_passthrough(self):
        html = "<p>Normal text</p>"
        result = _parse_newsletter_items(html)
        assert result == html


class TestInjectSectionIds:
    def test_adds_ids(self):
        html = "<h2>First</h2><p>text</p><h2>Second</h2>"
        result = _inject_section_ids(html)
        assert 'id="section-1"' in result
        assert 'id="section-2"' in result

    def test_no_h2_unchanged(self):
        html = "<h3>Not h2</h3>"
        result = _inject_section_ids(html)
        assert result == html

    def test_preserves_existing_attrs(self):
        html = '<h2 class="special">Title</h2>'
        result = _inject_section_ids(html)
        assert 'id="section-1"' in result
        assert "special" in result


class TestBuildNewsletterToc:
    def test_single_section_returns_empty(self):
        html = '<h2 id="section-1">Only One</h2>'
        assert _build_newsletter_toc(html) == ""

    def test_two_sections_builds_toc(self):
        html = '<h2 id="section-1">First</h2><p>x</p><h2 id="section-2">Second</h2>'
        toc = _build_newsletter_toc(html)
        assert "Contents" in toc
        assert "First" in toc
        assert "Second" in toc
        assert "#section-1" in toc
        assert "#section-2" in toc

    def test_strips_inner_tags(self):
        html = '<h2 id="section-1"><strong>Bold</strong></h2><h2 id="section-2">Plain</h2>'
        toc = _build_newsletter_toc(html)
        assert "Bold" in toc
        assert "<strong>" not in toc


class TestFormatContributors:
    def test_empty_list(self):
        assert _format_contributors([]) == ""

    def test_single_contributor(self):
        html = _format_contributors(["Alice"])
        assert "Alice" in html
        assert "Contributors" in html

    def test_multiple_contributors(self):
        html = _format_contributors(["Alice", "Bob", "Charlie"])
        assert "Alice, Bob, Charlie" in html
